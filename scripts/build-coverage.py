#!/usr/bin/env python3
"""Render the curriculum coverage matrix from curriculum/coverage.yaml.

Outputs
-------
* docs/appendices/coverage-matrix.md            - the full matrix (regenerated completely)
* docs/<section>/index.md                       - a topic table injected between
                                                  <!-- coverage:start --> and <!-- coverage:end -->

Usage
-----
    python scripts/build-coverage.py          # write outputs
    python scripts/build-coverage.py --check  # exit 1 if outputs are stale (used in CI)

The YAML file is the single source of truth. Edit it, then re-run this script.
"""
from __future__ import annotations

import argparse
import os
import sys
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
COVERAGE = ROOT / "curriculum" / "coverage.yaml"
DOCS = ROOT / "docs"
MATRIX = DOCS / "appendices" / "coverage-matrix.md"
START = "<!-- coverage:start -->"
END = "<!-- coverage:end -->"

STATUS_BADGE = {
    "Planned": ":material-circle-outline: Planned",
    "Outline": ":material-circle-slice-2: Outline",
    "Draft": ":material-circle-slice-5: Draft",
    "Reviewed": ":material-check-circle: Reviewed",
    "Needs update": ":material-alert-circle-outline: Needs update",
}


def load() -> dict:
    with COVERAGE.open(encoding="utf-8") as f:
        return yaml.safe_load(f)


def rel_link(from_md: Path, destination: str) -> str:
    """Relative Markdown link from a docs page to a destination path (repo-relative)."""
    target = ROOT / destination
    return os.path.relpath(target, from_md.parent).replace(os.sep, "/")


def page_cell(from_md: Path, topic: dict) -> str:
    destination = topic["destination"]
    exists = (ROOT / destination).is_file()
    if exists:
        return f"[{Path(destination).stem}]({rel_link(from_md, destination)})"
    return f"planned: `{destination.removeprefix('docs/')}`"


def section_table(data: dict, section: str, from_md: Path) -> str:
    rows = ["| ID | Topic | Status | Page |", "|---|---|---|---|"]
    for domain in data["domains"]:
        if domain["section"] != section:
            continue
        rows.append(f"| **{domain['id']}** | **{domain['title']}** | | |")
        for t in domain["topics"]:
            rows.append(
                f"| {t['id']} | {t['title']} | {STATUS_BADGE[t['status']]} | {page_cell(from_md, t)} |"
            )
    if len(rows) == 2:
        return "_No curriculum domains are mapped to this section yet._"
    return "\n".join(rows)


def matrix_page(data: dict) -> str:
    topics = [t for d in data["domains"] for t in d["topics"]]
    counts = Counter(t["status"] for t in topics)
    lines = [
        "---",
        "title: Curriculum coverage matrix",
        "description: Every topic from the master curriculum inventory mapped to its canonical page or planned destination.",
        "hide:",
        "  - toc",
        "---",
        "",
        "# Curriculum coverage matrix",
        "",
        "<!-- This file is generated by scripts/build-coverage.py from curriculum/coverage.yaml. Do not edit by hand. -->",
        "",
        "This matrix maps every topic bullet from the master curriculum inventory",
        "([MASTER_PROMPT.md, Section 8](https://github.com/vinay9354/architecture-atlas/blob/main/MASTER_PROMPT.md))",
        "to the page that teaches it, or to the planned destination where it will live.",
        "The **ID** is stable: use it in issues and pull requests.",
        "",
        f"**Last updated:** {data['last_updated']}  ",
        f"**Domains:** {len(data['domains'])} · **Topic entries:** {len(topics)}",
        "",
        "| Status | Count | Meaning |",
        "|---|---:|---|",
        f"| {STATUS_BADGE['Reviewed']} | {counts.get('Reviewed', 0)} | Technical accuracy, diagrams, references, and exercises checked |",
        f"| {STATUS_BADGE['Draft']} | {counts.get('Draft', 0)} | Content exists; needs technical and teaching review |",
        f"| {STATUS_BADGE['Outline']} | {counts.get('Outline', 0)} | Objectives and structure exist; explanation incomplete |",
        f"| {STATUS_BADGE['Planned']} | {counts.get('Planned', 0)} | Identified; destination page not yet written |",
        f"| {STATUS_BADGE['Needs update']} | {counts.get('Needs update', 0)} | May be stale or a reference changed |",
        "",
        "!!! note \"How to read the Page column\"",
        "    A link means the page exists. `planned: path` means the page does not exist yet;",
        "    the path is where it will be created. Pages are linked from their section index once written.",
        "",
    ]
    for domain in data["domains"]:
        dc = Counter(t["status"] for t in domain["topics"])
        written = sum(v for k, v in dc.items() if k != "Planned")
        lines += [
            f"## {domain['id']} — {domain['title']}",
            "",
            f"Section: [{domain['section']}](../{domain['section']}/index.md) · "
            f"{written}/{len(domain['topics'])} topic entries have a page",
            "",
            "| ID | Topic | Status | Page | Inventory (from the master curriculum) |",
            "|---|---|---|---|---|",
        ]
        for t in domain["topics"]:
            inv = " ".join(t["inventory"].split()).replace("|", "\\|")
            lines.append(
                f"| {t['id']} | {t['title']} | {STATUS_BADGE[t['status']]} | {page_cell(MATRIX, t)} | {inv} |"
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def inject(path: Path, table: str) -> str:
    text = path.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise SystemExit(f"{path}: missing {START} / {END} markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{START}\n{table}\n{END}{tail}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    args = parser.parse_args()

    data = load()
    outputs: dict[Path, str] = {MATRIX: matrix_page(data)}
    for section in sorted({d["section"] for d in data["domains"]}):
        index = DOCS / section / "index.md"
        if not index.exists():
            print(f"warning: {index} does not exist; skipping table injection", file=sys.stderr)
            continue
        outputs[index] = inject(index, section_table(data, section, index))

    stale = []
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")

    topics = [t for d in data["domains"] for t in d["topics"]]
    counts = Counter(t["status"] for t in topics)
    print(f"coverage: {len(data['domains'])} domains, {len(topics)} topics, {dict(counts)}")
    if args.check:
        if stale:
            for p in stale:
                print(f"STALE: {p.relative_to(ROOT)} (run scripts/build-coverage.py)")
            return 1
        print("coverage outputs are up to date")
    else:
        print(f"updated {len(stale)} file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
